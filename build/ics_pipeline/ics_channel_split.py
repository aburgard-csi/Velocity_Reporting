# ------------------------------------------------------------------ small readers
def _hash(v):
    s = str(v).strip().upper() if v is not None else ""
    return s if re.fullmatch(r"[0-9A-F]{40}", s) else ""


def _to_date(v):
    if isinstance(v, _dt.datetime):
        return v.date()
    if isinstance(v, _dt.date):
        return v
    if isinstance(v, str) and v.strip():
        s = v.strip().split(" ")[0]
        for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%m/%d/%y"):
            try:
                return _dt.datetime.strptime(s, fmt).date()
            except ValueError:
                pass
    return None


def month_of(label):
    """'Dec 22' / "Dec'22" / '2022-12' -> (2022, 12)."""
    d = P.parse_month(label)
    return (d.year, d.month) if d else None


def dm_list_is_program_to_date(path, banner):
    """True when the direct-mail list covers the whole program: its banner says `Period: PTD`, else its
    file name carries PTD. A list for one month (Brooks Bank 1537's is "Opened in Sep 2026") is not a
    program-to-date count, and treating it as one would call every earlier month's accounts branch referrals."""
    if banner:
        return banner.strip().lower() == "ptd"
    return re.search(r"\bptd\b", os.path.basename(str(path)), re.I) is not None


def read_dm_accounts(path):
    """-> ([(hash, open date, branch)], rows without a usable hash/date). The CSM's direct-mail list:
    header row carries 'Open Date' and 'Account Number'."""
    return read_dm_list(path)[:2]


def read_dm_list(path):
    """-> (accounts, rows unusable, the banner's `Period:` text or None) — see `read_dm_accounts`."""
    import openpyxl
    wb = openpyxl.load_workbook(str(path), read_only=True, data_only=True)
    try:
        rows = [tuple(r) for r in wb.worksheets[0].iter_rows(values_only=True)]
    finally:
        wb.close()
    hi = next((i for i, r in enumerate(rows[:30])
               if any(isinstance(v, str) and v.strip().lower() == "open date" for v in r)), None)
    if hi is None:
        return [], 0, None
    banner = None
    for r in rows[:hi]:
        for v in r:
            if isinstance(v, str) and v.strip().lower().startswith("period:"):
                banner = v.split(":", 1)[1].strip()
    hdr = [str(v).strip().lower() if v is not None else "" for v in rows[hi]]
    c_date = hdr.index("open date")
    c_hash = next((i for i, h in enumerate(hdr) if h in ("account number", "acct number", "hashed account")), None)
    c_br = next((i for i, h in enumerate(hdr) if h.startswith("branch")), None)
    out, bad = [], 0
    for r in rows[hi + 1:]:
        if not any(v not in (None, "") for v in r):
            continue
        d = _to_date(r[c_date]) if c_date < len(r) else None
        h = _hash(r[c_hash]) if (c_hash is not None and c_hash < len(r)) else ""
        if d is None:
            bad += 1
            continue
        br = ""
        if c_br is not None and c_br < len(r) and r[c_br] not in (None, ""):
            v = r[c_br]
            br = str(int(v)) if isinstance(v, float) and v.is_integer() else str(v).strip()
        out.append((h, d, br))
    return out, bad, banner


def referral_export_files(folder):
    """The all-clients referral export files in a folder, oldest first: the merged `ics_referrals.csv`
    and any dated landing (`ics_referrals <date>.csv`) the morning merge has not folded in yet."""
    if not folder or not os.path.isdir(str(folder)):
        return []
    fs = [f for f in glob.glob(os.path.join(str(folder), "ics_referrals*.csv"))
          if os.path.getsize(f) > 0 and not os.path.basename(f).startswith("~$")]
    # the merged file first, then landings by name (their dates sort): a later file's row for the same
    # referral replaces an earlier one, the rule scripts/ics_referrals_pull.py states for its merge
    return sorted(fs, key=lambda f: (os.path.basename(f) != "ics_referrals.csv", os.path.basename(f)))


def read_referral_export(files, cid):
    """-> [row dicts] for one client, de-duplicated by (account hash, issue date) with the LATER file
    winning. Reads utf-8 with or without a BOM. Rows are the export's own columns."""
    cid = str(cid)
    seen = {}
    for f in files:
        with open(f, encoding="utf-8-sig", newline="") as fh:
            for r in csv.DictReader(fh):
                if str(r.get("client_id", "")).strip() != cid:
                    continue
                seen[(str(r.get("primarydda", "")).strip().upper(), str(r.get("issue_date", "")).strip())] = r
    return list(seen.values())


def referral_events(rows):
    """[(issue date, branch key, id)] — the shape `ics_local_sheet.referral_sections` counts. One per
    referral: the account hash and issue time identify it."""
    out = []
    for r in rows:
        d = _to_date(r.get("issue_date"))
        if d is None:
            continue
        b = str(r.get("branch_number", "") or "").strip()
        b = "" if b.upper() == "NULL" else (str(int(b)) if b.isdigit() else b)
        out.append((d, b, f"{str(r.get('primarydda', '')).strip().upper()}|{r.get('issue_date')}"))
    return out


def referral_branch_names(rows):
    """{branch key: name} as the export names them (used only where the Goals tab does not)."""
    out = {}
    for r in rows:
        b = str(r.get("branch_number", "") or "").strip()
        n = str(r.get("branch_name", "") or "").strip()
        if b and b.upper() != "NULL" and n and n.upper() != "NULL":
            out.setdefault(str(int(b)) if b.isdigit() else b, n)
    return out


def referral_matched_accounts(rows):
    """{hash: date opened} for the referrals whose account the export found."""
    out = {}
    for r in rows:
        if str(r.get("account_found", "")).strip().upper() != "Y":
            continue
        h = _hash(r.get("primarydda"))
        d = _to_date(r.get("date_opened"))
        if h and d:
            out.setdefault(h, d)
    return out


# ------------------------------------------------------------------ the count split (pure)
def cohort_split(cohort_months, accounts, dm_accounts):
    """Split the workbook's accounts opened, cohort by cohort.

    `cohort_months` are the workbook's cohort labels ('Dec 22'), `accounts` its accounts opened per
    cohort, `dm_accounts` the direct-mail list as [(hash, date, branch)]. Direct mail = the list's
    accounts opened in the cohort's month; branch referral = the remainder (never below zero). Returns
    {"direct_mail": [...], "referral": [...], "dm_outside": n, "over": [months where the list exceeded
    the workbook]}. A list account dated before the first cohort or after the last is counted in
    `dm_outside` and left out of every cohort."""
    keys = [month_of(m) for m in cohort_months]
    idx = {k: i for i, k in enumerate(keys)}
    dm = [0] * len(keys)
    outside = 0
    for _, d, _b in dm_accounts:
        i = idx.get((d.year, d.month))
        if i is None:
            outside += 1
        else:
            dm[i] += 1
    ref, over = [], []
    for i, (a, k) in enumerate(zip(accounts, dm)):
        if k > a:
            over.append(cohort_months[i])
        ref.append(max(a - k, 0))
    return {"direct_mail": dm, "referral": ref, "dm_outside": outside, "over": over}


def program_year_sums(values, size=12):
    return [sum(values[i:i + size]) for i in range(0, len(values), size)]


# ------------------------------------------------------------------ the ODD scan
def _odd_member(z):
    names = [i.filename for i in z.infolist() if i.filename.lower().endswith(".csv")]
    pick = [n for n in names if re.search(r"odd", n, re.I) and "combined" not in n.lower()]
    return (pick or names or [None])[0]


def _num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return 0.0


def scan_odd(zip_path, groups):
    """Stream the ODD member of `zip_path` once and return the accounts whose hash is in `groups`
    ({hash: 'dm' | 'ref'}). -> {"months": ['2023-10', ...], "accounts": [...], "rows": n, "member": name,
    "stamp": '(MMDDYY_HHMMSS)' or None}. Each account: group, opened, closed, dob (ISO or None), business
    flag, product code and description, and monthly debit spend (signature + PIN dollars).
    Reads Latin-1 as the extracts are written; the one member is read, nothing is extracted to disk."""
    z = zipfile.ZipFile(str(zip_path))
    name = _odd_member(z)
    if name is None:
        raise ValueError(f"{zip_path}: no ODD .csv member")
    stamp = re.search(r"\((\d{6}_\d{6})\)", name)
    accounts, rows, months, cols = [], 0, [], None
    with z.open(name) as f:
        rd = csv.reader(io.TextIOWrapper(f, encoding="latin1", newline=""))
        hdr = None
        for k, row in enumerate(rd):
            if hdr is None:
                if k > 12:
                    raise ValueError(f"{name}: no 'Acct Number' header in the first rows")
                if any(str(c).strip().lower() in ("acct number", "account number") for c in row):
                    hdr = [str(c).strip() for c in row]
                    ih = {h: i for i, h in enumerate(hdr)}
                    mons = []
                    for h in hdr:
                        m = re.fullmatch(r"([A-Z][a-z]{2})(\d\d) Sig \$", h)
                        if m:
                            mons.append(m.group(1) + m.group(2))
                    mons = sorted(dict.fromkeys(mons),
                                  key=lambda s: (int(s[3:]), _dt.datetime.strptime(s[:3], "%b").month))
                    months = [f"20{s[3:]}-{_dt.datetime.strptime(s[:3], '%b').month:02d}" for s in mons]
                    cols = [(ih[f"{s} Sig $"], ih.get(f"{s} PIN $")) for s in mons]
                    c_hash = next(ih[h] for h in hdr if h.lower() in ("acct number", "account number"))
                    c = {n: ih.get(n) for n in ("Date Opened", "Date Closed", "DOB", "Business?", "Prod Code", "Prod Desc")}
                continue
            rows += 1
            h = row[c_hash].strip().upper() if c_hash < len(row) else ""
            g = groups.get(h)
            if g is None:
                continue
            at = lambda n: (row[c[n]].strip() if (c[n] is not None and c[n] < len(row)) else "")
            od, cd, dob = _to_date(at("Date Opened")), _to_date(at("Date Closed")), _to_date(at("DOB"))
            accounts.append({
                "hash": h, "group": g, "opened": od.isoformat() if od else None,
                "closed": cd.isoformat() if cd else None, "dob": dob.isoformat() if dob else None,
                "business": at("Business?").lower() in ("yes", "y"),
                "code": at("Prod Code"), "product": at("Prod Desc"),
                "spend": [round(_num(row[a]) + (_num(row[b]) if b is not None else 0.0), 2) if a < len(row) else 0.0
                          for a, b in cols],
            })
    return {"months": months, "accounts": accounts, "rows": rows, "member": name,
            "stamp": stamp.group(1) if stamp else None}


# ------------------------------------------------------------------ what the ODD and the workbook say together (pure)
def cohort_spend(scan, cohort_months):
    """-> {'dm': [spend per cohort], 'ref': [...], 'dm_n': [accounts per cohort], 'ref_n': [...]}:
    ODD debit spend in the scan's window, summed over the accounts opened in each workbook cohort,
    by channel. The cohort of an account is its ODD open month (the workbook's own)."""
    idx = {month_of(m): i for i, m in enumerate(cohort_months)}
    n = len(cohort_months)
    out = {"dm": [0.0] * n, "ref": [0.0] * n, "dm_n": [0] * n, "ref_n": [0] * n}
    for a in scan["accounts"]:
        o = _to_date(a["opened"])
        i = idx.get((o.year, o.month)) if o else None
        if i is None:
            continue
        out[a["group"]][i] += sum(a["spend"])
        out[a["group"] + "_n"][i] += 1
    return out


def implied_rate(cohort_months, wb_interchange, wb_accounts, spend, window_first):
    """The blended interchange rate the workbook implies, or None when it is not stable.

    Workbook interchange per cohort divided by the ODD's debit spend for the accounts of that cohort. A
    cohort opened on or after `window_first` (the ODD's first month, (year, month)) has its whole history
    in the ODD, so the ratio is that cohort's rate. The cohorts used are those whose ODD-matched accounts
    cover at least 90% of the workbook's accounts. The pooled rate is returned only when every such cohort
    is within 5% of it: on KEMBA CU 1195 all 35 are within 0.1% of 0.900%, which is what lets the ODD's
    spend stand for the workbook's interchange. -> {"rate", "rate_min", "rate_max", "cohorts_used"}."""
    keys = [month_of(m) for m in cohort_months]
    full = []
    for i in range(len(keys)):
        if keys[i] is None or keys[i] < window_first:
            continue
        sp = spend["dm"][i] + spend["ref"][i]
        covered = (spend["dm_n"][i] + spend["ref_n"][i]) >= ODD_FIRST_FULL_COVERAGE * (wb_accounts[i] or 0)
        if sp > 0 and wb_interchange[i] > 0 and covered:
            full.append(i)
    if not full:
        return None
    pooled = sum(wb_interchange[i] for i in full) / sum(spend["dm"][i] + spend["ref"][i] for i in full)
    rates = [wb_interchange[i] / (spend["dm"][i] + spend["ref"][i]) for i in full]
    if max(abs(r - pooled) / pooled for r in rates) > RATE_SPREAD_LIMIT:
        return None
    return {"rate": pooled, "rate_min": min(rates), "rate_max": max(rates), "cohorts_used": len(full)}


def gap_months(months):
    """Calendar months missing between the first and last of `months` ('YYYY-MM' strings): the ODD can
    carry no debit-dollar columns for some months (KEMBA's May-Aug 2026), and spend there is unknown,
    not zero."""
    if not months:
        return []
    have = {tuple(int(x) for x in m.split("-")) for m in months}
    y, m = (int(x) for x in months[0].split("-"))
    end = tuple(int(x) for x in months[-1].split("-"))
    out = []
    while (y, m) <= end:
        if (y, m) not in have:
            out.append(f"{y}-{m:02d}")
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


def exposure_by_year(scan, rate):
    """Debit spend, interchange and open account-months by channel and calendar year, over the months the
    ODD carries debit dollars for. An account is open in a month when it was opened before the month ends
    and not closed before it starts. Interchange = spend x `rate` (the workbook's implied blended rate).

    -> [{"label": '2024', "months": n observed, "dm": {"spend", "interchange", "account_months", "active",
    "pam"}, "ref": {...}}], oldest first, then {"all": the same over every observed month}. Interchange per
    account per month (`pam`) = interchange / account-months in the same months; `active` = account-months
    with any spend, so a reader can see how many open accounts used their card."""
    months = scan["months"]
    ym = [tuple(int(x) for x in m.split("-")) for m in months]
    acc = {"dm": [[0.0, 0, 0] for _ in months], "ref": [[0.0, 0, 0] for _ in months]}   # spend, open, active
    for a in scan["accounts"]:
        o, c = _to_date(a["opened"]), _to_date(a["closed"])
        if o is None:
            continue
        for i, (y, m) in enumerate(ym):
            if (o.year, o.month) > (y, m):
                continue                      # opened after this month ended
            if c is not None and (c.year, c.month) < (y, m):
                continue                      # closed before it began
            sp = a["spend"][i]
            cell = acc[a["group"]][i]
            cell[0] += sp
            cell[1] += 1
            cell[2] += 1 if sp > 0 else 0
    def fold(idx):
        out = {"months": len(idx)}
        for g in ("dm", "ref"):
            sp = sum(acc[g][i][0] for i in idx); am = sum(acc[g][i][1] for i in idx); ac = sum(acc[g][i][2] for i in idx)
            out[g] = {"spend": round(sp, 2), "interchange": round(sp * rate, 2), "account_months": am, "active": ac,
                      "pam": (sp * rate / am if am else 0.0)}
        return out
    years = sorted({y for y, _ in ym})
    yrs = []
    for y in years:
        idx = [i for i, (yy, _) in enumerate(ym) if yy == y]
        r = fold(idx); r["label"] = str(y); r["first"] = months[idx[0]]; r["last"] = months[idx[-1]]
        yrs.append(r)
    allr = fold(list(range(len(months)))); allr["first"] = months[0]; allr["last"] = months[-1]
    return {"years": yrs, "all": allr}


def age_profile(scan, as_of):
    """Age of the ICS accounts at `as_of` (a date), personal accounts only: a business row's date of
    birth cell is a company date (a 2015 open date on a business product in KEMBA's extract). Blank,
    future and over-110 dates are left out and counted. -> {"counts": {bucket: n}, "pct": {...},
    "n": n, "excluded": {...}, "mean": years, "share_44_or_younger": 0..1}."""
    counts = {lab: 0 for _, _, lab in AGE_EDGES}
    ex = {"business": 0, "no_dob": 0, "implausible": 0}
    ages = []
    for a in scan["accounts"]:
        if a["business"]:
            ex["business"] += 1
            continue
        dob = _to_date(a["dob"])
        if dob is None:
            ex["no_dob"] += 1
            continue
        age = (as_of - dob).days / 365.25
        if age < 0 or age > 110:
            ex["implausible"] += 1
            continue
        ages.append(age)
        for lo, hi, lab in AGE_EDGES:
            if lo <= int(age) <= hi:
                counts[lab] += 1
                break
    n = sum(counts.values())
    pct = {k: (v / n if n else 0.0) for k, v in counts.items()}
    young = sum(counts[l] for _, hi, l in AGE_EDGES if hi <= 44)
    return {"counts": counts, "pct": pct, "n": n, "excluded": ex,
            "mean": (sum(ages) / len(ages) if ages else None),
            "share_44_or_younger": (young / n if n else 0.0)}


def product_mix(scan):
    """-> [{"product", "code", "direct_mail", "referral", "total"}] — every ICS account found in the ODD
    (closed ones too: program to date), by the ODD's product description, largest first."""
    agg = {}
    for a in scan["accounts"]:
        key = (a["product"] or "Unknown", a["code"] or "")
        r = agg.setdefault(key, {"product": key[0], "code": key[1], "direct_mail": 0, "referral": 0})
        r["direct_mail" if a["group"] == "dm" else "referral"] += 1
    out = list(agg.values())
    for r in out:
        r["total"] = r["direct_mail"] + r["referral"]
    return sorted(out, key=lambda r: (-r["total"], r["product"]))


# ------------------------------------------------------------------ files + cache
def _stat_key(*paths):
    h = hashlib.sha1()
    for p in paths:
        try:
            st = os.stat(p)
            h.update(f"{os.path.basename(p)}|{st.st_size}|{int(st.st_mtime)}".encode())
        except OSError:
            h.update(b"-")
    h.update(str(SCAN_VERSION).encode())
    return h.hexdigest()[:16]


def _cache_dir():
    d = os.environ.get("ICS_SPLIT_CACHE")
    if d:
        return d
    try:
        import rpe_env
        return str(rpe_env.build_artifacts() / "ics_split")
    except BaseException:
        return None


def _cached_scan(cid, odd_zip, groups, key_paths, log):
    cache = _cache_dir()
    key = _stat_key(odd_zip, *key_paths)
    path = os.path.join(cache, f"{cid}_{key}.json") if cache else None
    if path and os.path.isfile(path):
        try:
            with open(path, encoding="utf-8") as fh:
                return json.load(fh), True
        except (OSError, ValueError):
            pass
    log(f"ICS channel split: scanning {os.path.basename(odd_zip)} for {len(groups):,} list accounts (about a minute)")
    scan = scan_odd(odd_zip, groups)
    if path:
        try:
            os.makedirs(cache, exist_ok=True)
            with open(path + ".tmp", "w", encoding="utf-8") as fh:
                json.dump(scan, fh)
            os.replace(path + ".tmp", path)
        except OSError:
            pass
    return scan, False


