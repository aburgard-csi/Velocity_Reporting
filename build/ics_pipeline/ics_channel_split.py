#!/usr/bin/env python3
"""
ics_channel_split.py — direct mail and branch referrals, told apart.

Cindy Draper's review of KEMBA CU 1195 (2026-11-03): "she wants to SEE THE SPLIT between direct mail and
branch referrals", and the deck should "highlight revenue generated by referrals from early in the
program". The ICS workbook counts ONE number for both ("the accounts that matched in the workbook for
both mail and referrals", Cindy), so the split comes from the lists beside it. What each source can and
cannot tell is the whole point of this module, so it is stated here once:

  MEASURED
    * Direct-mail accounts by month opened: the CSM's `Inputs/ICS Direct Mail/` list, one row per
      account (hashed account number, open date, branch).
    * Branch referrals by issue date and branch: the all-clients referral export
      (`Inputs/ICS Referrals/ics_referrals*.csv`). For KEMBA it reproduces the VIP referral dashboard
      exactly (Whitehall 128, Pickerington 117 ... 831 year to date at 2026-10-13), which is why it is
      the referral source where no VIP sheet exists. `account_found` / `date_opened` carry the
      referral's account when one has been matched.
    * Debit card spend by account and month, and age, product and open/close dates: the ODD extract
      (`Inputs/ODDD/<id>_ODDD.zip`), joined to both lists on the account hash.
  DERIVED
    * Branch-referral accounts by cohort = the workbook's accounts opened less the direct-mail list's
      accounts for that month. The referral file's own matched accounts agree within a few percent
      (KEMBA: 3,221 against 3,148); the difference is stated, not hidden.
    * Interchange by channel: workbook interchange per cohort equals ODD spend x ONE blended rate. On
      KEMBA that rate is 0.900% in every cohort opened since the ODD begins (Oct 2023), to the
      third decimal, which is what makes the split a measurement rather than a guess. The rate is
      derived per client and checked for stability before any dollar is printed; a client whose rate
      is not stable gets no interchange split. Interchange per ACCOUNT per month is then the ODD's spend x
      that rate over the accounts open in each calendar month (opened before it ends, not closed before it
      starts), by channel — never the workbook's per-cohort figures, which carry no channel. The ODD can
      lack debit-dollar columns for some months (KEMBA: May-Aug 2026); those months are named, not zeroed.
      KEMBA's result is the opposite of the 2026-11-03 working note that direct mail runs higher: referral
      accounts earn $8.15 per open account-month against $7.37 for direct mail, and 61% of their
      account-months show debit spend against 49%.
  NOT SPLITTABLE
    * Spread, NSF/OD and other fees. The workbook reports them for all ICS accounts together and the ODD
      carries no fee or balance history to rebuild them. The slides say so in one sentence.

An account on BOTH lists is counted once, as direct mail (the workbook counts it once, and the
referral figure is the remainder after direct mail). The count is stated in the notes.

Import-safe: nothing runs at import. Everything but `scan_odd` / the file readers is a pure function of
its arguments, so the tests use synthetic lists.
"""
