def _format_excel_table(excel_path: Path, sheet_name: str, df: pd.DataFrame) -> None:
    book = load_workbook(excel_path)
    if sheet_name not in book.sheetnames:
        raise KeyError(f"Sheet '{sheet_name}' not found in {excel_path}")
    sheet = book[sheet_name]

    styles = _define_excel_styles()
    n_rows, n_cols = df.shape
    if n_rows == 0 or n_cols == 0:
        book.save(excel_path)
        return

    _format_header_row(sheet, df.columns, styles)
    _format_data_rows(sheet, df, styles)
    _apply_sheet_formatting(sheet, n_rows, n_cols)

    book.save(excel_path)
    book.close()


def _define_excel_styles() -> dict:
    thin = Side(style="thin", color="D9D9D9")
    return {
        "header_fill": PatternFill(start_color="CCE5FF", end_color="CCE5FF", fill_type="solid"),
        "total_fill": PatternFill(start_color="F0F0F0", end_color="F0F0F0", fill_type="solid"),
        "zebra_fill": PatternFill(start_color="FAFAFA", end_color="FAFAFA", fill_type="solid"),
        "header_font": Font(bold=True, size=11),
        "data_font": Font(size=10),
        "total_font": Font(bold=True, size=10),
        "center_align": Alignment(horizontal="center", vertical="center", wrap_text=False),
        "left_align": Alignment(horizontal="left", vertical="center", wrap_text=False),
        "right_align": Alignment(horizontal="right", vertical="center", wrap_text=False),
        "border": Border(left=thin, right=thin, top=thin, bottom=thin),
    }


def _format_header_row(sheet, columns, styles) -> None:
    # Note: header is written at row 3 by add_analysis_to_report (title at
    # row 1), so this writes into row 1 of a *fresh* format pass -- kept
    # matching the notebook's row-3 offset by calling this against the
    # sheet's existing row-3 header instead of overwriting row 1.
    header_row = 3
    for c, col_name in enumerate(columns, 1):
        cell = sheet.cell(row=header_row, column=c)
        cell.value = col_name
        cell.fill = styles["header_fill"]
        cell.font = styles["header_font"]
        cell.alignment = styles["center_align"]
        cell.border = styles["border"]


def _format_data_rows(sheet, df, styles) -> None:
    n_rows, n_cols = df.shape
    data_start_row = 4  # title row 1, header row 3, data from row 4

    for r in range(n_rows):
        excel_row = data_start_row + r
        is_total_row = _is_total_row(df.iloc[r], df.columns[0])

        if is_total_row:
            row_fill = styles["total_fill"]
        elif r % 2 == 1:
            row_fill = styles["zebra_fill"]
        else:
            row_fill = None

        for c in range(n_cols):
            _format_cell(
                sheet.cell(row=excel_row, column=c + 1),
                df.iloc[r, c],
                df.columns[c],
                c == 0,
                is_total_row,
                row_fill,
                styles,
            )


def _format_cell(cell, value, col_name, is_first_column, is_total_row, row_fill, styles) -> None:
    if row_fill:
        cell.fill = row_fill
    cell.border = styles["border"]
    cell.font = styles["total_font"] if is_total_row else styles["data_font"]

    if pd.isna(value):
        cell.value = None
        cell.alignment = styles["center_align"]
        return

    if is_first_column:
        cell.alignment = styles["left_align"]
    elif isinstance(value, (int, float)):
        cell.alignment = styles["right_align"]
    else:
        cell.alignment = styles["center_align"]

    if isinstance(value, (int, float)):
        _apply_number_format(cell, value, col_name)
    else:
        cell.value = str(value)


def _apply_number_format(cell, value, col_name: str) -> None:
    count_columns = {
        "Accounts", "# of Accounts", "# of Items", "# of Paid Items",
        "Total OD/NSF Items", "# of Items Paid",
    }

    # A ratio is a percentage. "Pay Ratio" carried the numeric default and
    # printed 1.00 where the reader wanted 100% (James, 2026-09-09) -- the
    # column next to it, "% of Items", was formatted correctly, which made
    # the inconsistency look deliberate.
    if col_name.strip().lower().endswith("ratio") and col_name != "% Pay Rate":
        cell.value = float(value)
        cell.number_format = "0.0%"
    elif "%" in col_name and col_name != "% Pay Rate":
        cell.value = float(value) / 100.0
        cell.number_format = "0.0%"
    elif col_name == "% Pay Rate":
        cell.value = float(value)
        cell.number_format = "0%"
    elif col_name in count_columns:
        cell.value = int(round(value))
        cell.number_format = "#,##0"
    elif "$$" in col_name or col_name == "Average of OD Limit":
        cell.value = float(value)
        cell.number_format = "$#,##0" if abs(value) >= 1000 else "$#,##0.00"
    elif col_name == "Average of Swipes":
        cell.value = int(round(value))
        cell.number_format = "#,##0"
    elif col_name == "Pay Ratio":
        cell.value = float(value)
        cell.number_format = "0.00"
    elif any(term in col_name.lower() for term in ["avg", "med"]):
        cell.value = float(value)
        cell.number_format = "#,##0.00"
    else:
        cell.value = float(value)
        cell.number_format = "#,##0.00" if abs(value) >= 1000 else "0.00"


def _is_total_row(row_data, first_col_name) -> bool:
    first_val = str(row_data[first_col_name]).lower()
    return any(term in first_val for term in ["total", "grand total", "summary"])


def _apply_sheet_formatting(sheet, n_rows: int, n_cols: int) -> None:
    header_row = 3
    data_end_row = header_row + n_rows

    sheet.freeze_panes = f"A{header_row + 1}"
    sheet.auto_filter.ref = f"A{header_row}:{sheet.cell(row=data_end_row, column=n_cols).coordinate}"

    min_width, max_width = 10, 50
    for col_idx in range(1, n_cols + 1):
        column_letter = sheet.cell(row=header_row, column=col_idx).column_letter
        max_length = len(str(sheet.cell(row=header_row, column=col_idx).value or ""))

        for row_idx in range(header_row + 1, data_end_row + 1):
            cell_value = sheet.cell(row=row_idx, column=col_idx).value
            if cell_value:
                display_length = len(str(cell_value))
                if isinstance(cell_value, (int, float)):
                    display_length += 3
                max_length = max(max_length, display_length)

        optimal_width = max_length + 2
        sheet.column_dimensions[column_letter].width = max(min_width, min(max_width, optimal_width))
