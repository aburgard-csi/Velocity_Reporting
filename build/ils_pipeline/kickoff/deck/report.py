def create_report(client_id: str, output_dir: Path, total_accounts: int, source_file_name: str) -> Path:
    """Create the master workbook with a cover 'Report Info' sheet."""
    now = datetime.now()
    month_abbr = calendar.month_abbr[now.month].upper()
    year_short = str(now.year)[-2:]

    report_filename = f"{client_id} - ILS Kickoff Report Data-{month_abbr}{year_short}.xlsx"
    report_path = Path(output_dir) / report_filename

    wb = Workbook()
    if "Sheet" in wb.sheetnames:
        wb.remove(wb["Sheet"])

    cover = wb.create_sheet("Report Info")
    cover["A1"] = "ILS Kickoff Report"
    cover["A1"].font = Font(size=20, bold=True)
    cover["A3"] = "Report Details:"
    cover["A3"].font = Font(size=14, bold=True)

    report_info = [
        ("Client ID:", client_id),
        ("Report Date:", now.strftime("%B %d, %Y")),
        ("Source File:", Path(source_file_name).name),
        ("Total Accounts:", f"{total_accounts:,}"),
        ("Report Period:", f"{month_abbr} {now.year}"),
        ("Generated By:", "ILS Kickoff Toolkit"),
    ]
    for i, (label, value) in enumerate(report_info, start=4):
        cover[f"A{i}"] = label
        cover[f"A{i}"].font = Font(bold=True)
        cover[f"B{i}"] = value

    cover.column_dimensions["A"].width = 20
    cover.column_dimensions["B"].width = 40

    wb.save(report_path)
    wb.close()
    return report_path


def add_analysis_to_report(report_path: Path, sheet_name: str, data_df: pd.DataFrame,
                            charts: list[tuple[str, str]] | None = None) -> None:
    """Add one analysis tab (data table + optional charts) to the report."""
    wb = load_workbook(report_path)
    if sheet_name in wb.sheetnames:
        wb.remove(wb[sheet_name])
    ws = wb.create_sheet(sheet_name)

    ws["A1"] = sheet_name
    ws["A1"].font = Font(size=16, bold=True)

    start_row = 3
    for r_idx, row in enumerate(dataframe_to_rows(data_df, index=False, header=True)):
        for c_idx, value in enumerate(row, 1):
            ws.cell(row=start_row + r_idx, column=c_idx, value=value)

    wb.save(report_path)
    wb.close()

    _format_excel_table(report_path, sheet_name, data_df)

    if charts:
        wb = load_workbook(report_path)
        ws = wb[sheet_name]
        table_end_row = start_row + len(data_df) + 3

        for i, (chart_file, chart_title) in enumerate(charts):
            if os.path.exists(chart_file):
                img = XLImage(chart_file)
                img.width = 600
                img.height = 360

                col = "A" if i % 2 == 0 else "J"
                row = table_end_row + (i // 2) * 25

                ws[f"{col}{row - 1}"] = chart_title
                ws[f"{col}{row - 1}"].font = Font(size=12, bold=True)
                ws.add_image(img, f"{col}{row}")

        wb.save(report_path)
        wb.close()


